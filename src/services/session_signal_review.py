"""Bounded, source-constrained RunPod review of a user-selected connection.

No session profile is saved. Only validated evidence-anchored model reviews are
cached by connection/source/model, never assumed to be ground truth.
"""
from __future__ import annotations

import re
import hashlib
import json
from pydantic import BaseModel, ConfigDict, Field
from src.services.skill_connections import get_saved_skill_connections
from src.services.session_signal_adapter import SessionSignalProfile, _resolved_skill
from src.services.connection_model import _run, model_name
from src.services.storage import connection, initialize_database


class SessionReviewRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")
    profile: SessionSignalProfile
    connection_id: str = Field(min_length=10, max_length=80)


class SessionReviewError(ValueError):
    pass


REVIEW_PROMPT_VERSION = "v5-source-relationship-2"


def _cached_review(cache_key: str) -> dict | None:
    initialize_database()
    with connection() as db:
        db.execute("""CREATE TABLE IF NOT EXISTS signal_session_review_cache (
            cache_key TEXT PRIMARY KEY,
            evidence_version TEXT NOT NULL,
            payload TEXT NOT NULL,
            created_at TEXT NOT NULL
        )""")
        row = db.execute("SELECT payload FROM signal_session_review_cache WHERE cache_key = ?", (cache_key,)).fetchone()
    return json.loads(row["payload"]) if row else None


def _store_review(cache_key: str, version: str, payload: dict) -> None:
    # The payload contains evidence judgments only; no session names, tasks,
    # occupation, aspiration, email, CV or other profile fields are retained.
    with connection() as db:
        db.execute("INSERT OR IGNORE INTO signal_session_review_cache "
                   "(cache_key, evidence_version, payload, created_at) VALUES (?, ?, ?, datetime('now'))",
                   (cache_key, version, json.dumps(payload, ensure_ascii=False)))


def review_connection(request: SessionReviewRequest) -> dict:
    skill_ids = {resolved["id"] for skill in request.profile.skills
                 if (resolved := _resolved_skill(skill))["id"]}
    version, connections = get_saved_skill_connections()
    match = next((item for item in connections if
                  item.get("id") == request.connection_id and
                  item.get("current_skill_id") in skill_ids), None)
    if match is None:
        raise SessionReviewError("The connection isn't available for the selected session skill.")
    sources = []
    for entry in match.get("evidence", [])[:2]:
        old = str(entry.get("source_quote") or "").strip()[:400]
        ai = str(entry.get("ai_quote") or "").strip()[:400]
        if old and ai:
            sources.append({"id": str(entry.get("id", ""))[:120],
                            "existing_skill_passage": old, "ai_task_passage": ai})
    if not sources:
        raise SessionReviewError("Saved source passages are unavailable.")
    facts = {"existing_skill": match["current_skill_name"],
             "ai_capability": match["ai_skill"]["name"],
             "evidence_basis": match["basis"],
             "source_passages": sources}
    prompt = (
        "Evaluate whether the worker actually uses the existing skill in work related to the stated AI capability. "
        "Mentions in the same posting are not necessarily related. Distinguish duties and required skills "
        "from examples of a product's output, vendor marketing, qualifications and unrelated activities. "
        "A customer-support response generated by an AI system is NOT evidence that the worker uses customer-service skills. "
        "Do not infer a skill was used for an AI task solely because both appear in one job ad. "
        "Return JSON only with decision (related_workflow, unrelated or insufficient), "
        "rationale (one short sentence), learning_gap (short string), next_step (short string), "
        "and evidence_ids (array of supplied source ids). "
        "Use related_workflow only if the passages plausibly describe connecting work activities within "
        "the same role. Clearly call it a potential link, not a proven transition. "
        "Use unrelated for demonstrably mismatched roles; insufficient if ambiguous. "
        "No invented quotes, figures, employer claims or guaranteed outcomes."
    )
    cache_key = hashlib.sha256(json.dumps({
        "version": version, "connection": match["id"],
        "source_passages": sources, "prompt_version": REVIEW_PROMPT_VERSION,
        "model": model_name(),
    }, sort_keys=True, ensure_ascii=False).encode("utf-8")).hexdigest()
    cached = _cached_review(cache_key)
    if cached:
        return {**cached, "status": "cached"}
    status, result = _run(facts, prompt)
    if status != "generated":
        return {"status": status}
    if not isinstance(result, dict):
        return {"status": "invalid_output"}
    decision = result.get("decision")
    if decision not in {"related_workflow", "unrelated", "insufficient"}:
        return {"status": "rejected"}
    limits = {"rationale": 340, "learning_gap": 200, "next_step": 200}
    for key, limit in limits.items():
        val = result.get(key)
        if not isinstance(val, str) or len(val) > limit or (key == "rationale" and not val.strip()):
            return {"status": "rejected"}
        if re.search(r"\b(?:guaranteed|proves?|will replace|certainly|100% certain)\b", val, re.I):
            return {"status": "rejected"}
    allowed = {row["id"] for row in sources}
    refs = result.get("evidence_ids")
    if not isinstance(refs, list) or len(refs) > 2 or any(not isinstance(ref, str) or ref not in allowed for ref in refs):
        return {"status": "rejected"}
    if decision == "related_workflow" and not refs:
        return {"status": "rejected"}
    accepted = {"status": "generated", "decision": decision,
                "rationale": result["rationale"].strip(),
                "learning_gap": result["learning_gap"].strip(),
                "next_step": result["next_step"].strip(),
                "evidence_ids": refs,
                "review_origin": "RunPod GLM · automated interpretation, not human validation",
                "evidence_version": version}
    _store_review(cache_key, version, accepted)
    return accepted
